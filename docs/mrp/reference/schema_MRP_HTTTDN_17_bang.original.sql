CREATE PROCEDURE sp_kiem_tra_dong_xuat(IN p_PX INT,IN p_Type VARCHAR(20),IN p_YC INT)
BEGIN
 IF NOT EXISTS(SELECT 1 FROM CT_PHIEU_XUAT WHERE MaPX=p_PX) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu xuat chua co dong'; END IF;
 IF EXISTS(SELECT 1 FROM CT_PHIEU_XUAT c JOIN SAN_PHAM s ON s.MaSP=c.MaSP WHERE c.MaPX=p_PX AND (s.TrangThai<>'HOAT_DONG' OR (p_Type='CAP_PHAT' AND s.LoaiMatHang<>'NGUYEN_LIEU') OR (p_Type='THANH_PHAM' AND s.LoaiMatHang<>'THANH_PHAM'))) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Sai loai mat hang xuat'; END IF;
 IF p_Type='CAP_PHAT' THEN
 IF NOT EXISTS(SELECT 1 FROM CT_NHU_CAU_LAP_RAP WHERE MaYC=p_YC) OR
 EXISTS(SELECT 1 FROM CT_NHU_CAU_LAP_RAP n LEFT JOIN (SELECT MaSP,SUM(SoLuongXuat) SL FROM CT_PHIEU_XUAT WHERE MaPX=p_PX GROUP BY MaSP) x ON x.MaSP=n.MaSPLinhKien WHERE n.MaYC=p_YC AND COALESCE(x.SL,0)<>n.SoLuongCan) OR
 EXISTS(SELECT 1 FROM CT_PHIEU_XUAT x WHERE x.MaPX=p_PX AND NOT EXISTS(SELECT 1 FROM CT_NHU_CAU_LAP_RAP n WHERE n.MaYC=p_YC AND n.MaSPLinhKien=x.MaSP)) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phai cap du dung nhu cau da chot'; END IF;
 END IF;
END$$


