SET NAMES utf8mb4;
SET time_zone='+07:00';
SET SESSION sql_mode='STRICT_TRANS_TABLES,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION';


CREATE TABLE NHAN_VIEN (
 MaNV INT PRIMARY KEY AUTO_INCREMENT,
 HoTen VARCHAR(100) NOT NULL,
 ChucVu VARCHAR(50), SoDienThoai VARCHAR(20),
 TrangThai ENUM('DANG_LAM','NGUNG_LAM') NOT NULL DEFAULT 'DANG_LAM'
) ENGINE=InnoDB;


CREATE TABLE TAI_KHOAN (
 MaTK INT PRIMARY KEY AUTO_INCREMENT,
 MaNV INT NOT NULL UNIQUE,
 TenDangNhap VARCHAR(100) NOT NULL UNIQUE,
 MatKhauBam VARCHAR(255) NOT NULL,
 VaiTro ENUM('ADMIN','QUAN_LY_KHO','NHAN_VIEN') NOT NULL,
 TrangThai ENUM('HOAT_DONG','KHOA') NOT NULL DEFAULT 'HOAT_DONG',
 NgayTao DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV)
) ENGINE=InnoDB;


CREATE TABLE LOAI_SAN_PHAM (
 MaLoai INT PRIMARY KEY AUTO_INCREMENT, TenLoai VARCHAR(100) NOT NULL, MoTa VARCHAR(255)
) ENGINE=InnoDB;


CREATE TABLE SAN_PHAM (
 MaSP INT PRIMARY KEY AUTO_INCREMENT, MaLoai INT NOT NULL,
 SKU VARCHAR(50) NOT NULL UNIQUE, TenSP VARCHAR(200) NOT NULL,
 LoaiMatHang ENUM('NGUYEN_LIEU','THANH_PHAM') NOT NULL,
 DonViTinh VARCHAR(20) NOT NULL DEFAULT 'cai', MoTa TEXT,
 TrangThai ENUM('HOAT_DONG','NGUNG') NOT NULL DEFAULT 'HOAT_DONG',
 FOREIGN KEY (MaLoai) REFERENCES LOAI_SAN_PHAM(MaLoai)
) ENGINE=InnoDB;


CREATE TABLE NHA_CUNG_CAP (
 MaNCC INT PRIMARY KEY AUTO_INCREMENT, TenNCC VARCHAR(150) NOT NULL,
 SoDienThoai VARCHAR(20), DiaChi VARCHAR(255),
 TrangThai ENUM('HOAT_DONG','NGUNG') NOT NULL DEFAULT 'HOAT_DONG'
) ENGINE=InnoDB;


CREATE TABLE VI_TRI_KHO (
 MaViTri INT PRIMARY KEY AUTO_INCREMENT, MaViTriHienThi VARCHAR(50) NOT NULL UNIQUE,
 KhuVuc VARCHAR(50), Ke VARCHAR(50), Tang VARCHAR(50),
 TrangThai ENUM('HOAT_DONG','NGUNG') NOT NULL DEFAULT 'HOAT_DONG'
) ENGINE=InnoDB;


CREATE TABLE TON_KHO (
 MaTonKho INT PRIMARY KEY AUTO_INCREMENT, MaSP INT NOT NULL, MaViTri INT NOT NULL,
 SoLuongThucTe INT NOT NULL DEFAULT 0,
 SoLuongKhongBan INT NOT NULL DEFAULT 0,
 SoLuongKhaDung INT GENERATED ALWAYS AS (SoLuongThucTe-SoLuongKhongBan) STORED,
 NgayCapNhat DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), NguoiCapNhat INT,
 UNIQUE (MaSP,MaViTri),
 FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP),
 FOREIGN KEY (MaViTri) REFERENCES VI_TRI_KHO(MaViTri),
 FOREIGN KEY (NguoiCapNhat) REFERENCES NHAN_VIEN(MaNV),
 CONSTRAINT CK_TON CHECK (SoLuongThucTe>=0 AND SoLuongKhongBan>=0 AND SoLuongKhongBan<=SoLuongThucTe)
) ENGINE=InnoDB;


CREATE TABLE BOM (
 MaBOM INT PRIMARY KEY AUTO_INCREMENT, MaSPThanhPham INT NOT NULL,
 PhienBan INT NOT NULL, TenCauHinh VARCHAR(200) NOT NULL,
 TrangThai ENUM('NHAP','DANG_AP_DUNG','NGUNG') NOT NULL DEFAULT 'NHAP',
 MaNVLap INT NOT NULL, NgayBanHanh DATETIME(6),
 MaSPDangApDung INT GENERATED ALWAYS AS (CASE WHEN TrangThai='DANG_AP_DUNG' THEN MaSPThanhPham ELSE NULL END) STORED,
 UNIQUE (MaSPThanhPham,PhienBan), UNIQUE (MaSPDangApDung),
 FOREIGN KEY (MaSPThanhPham) REFERENCES SAN_PHAM(MaSP), FOREIGN KEY (MaNVLap) REFERENCES NHAN_VIEN(MaNV),
 CONSTRAINT CK_BOM_PB CHECK (PhienBan>0)
) ENGINE=InnoDB;


CREATE TABLE CT_BOM (
 MaBOM INT NOT NULL, MaSPLinhKien INT NOT NULL, DinhMuc INT NOT NULL,
 PRIMARY KEY (MaBOM,MaSPLinhKien),
 FOREIGN KEY (MaBOM) REFERENCES BOM(MaBOM), FOREIGN KEY (MaSPLinhKien) REFERENCES SAN_PHAM(MaSP),
 CONSTRAINT CK_BOM_DM CHECK (DinhMuc>0)
) ENGINE=InnoDB;


CREATE TABLE YEU_CAU_LAP_RAP (
 MaYC INT PRIMARY KEY AUTO_INCREMENT, MaBOM INT NOT NULL,
 SoLuongYeuCau INT NOT NULL, MaNVGiao INT NOT NULL, MaNVNhan INT NOT NULL,
 HanMongMuon DATETIME, NgayGiao DATETIME(6), DaNhanViec BOOLEAN NOT NULL DEFAULT FALSE,
 TrangThai ENUM('NHAP','DA_GIAO','DA_CAP_VAT_LIEU','DANG_LAP_RAP','HOAN_THANH','HUY') NOT NULL DEFAULT 'NHAP',
 LyDoHuy VARCHAR(255),
 FOREIGN KEY (MaBOM) REFERENCES BOM(MaBOM), FOREIGN KEY (MaNVGiao) REFERENCES NHAN_VIEN(MaNV), FOREIGN KEY (MaNVNhan) REFERENCES NHAN_VIEN(MaNV),
 INDEX IX_YC_NV (MaNVNhan,TrangThai), CONSTRAINT CK_YC_SL CHECK (SoLuongYeuCau>0 AND DaNhanViec IN(0,1))
) ENGINE=InnoDB;


CREATE TABLE CT_NHU_CAU_LAP_RAP (
 MaYC INT NOT NULL, MaSPLinhKien INT NOT NULL, DinhMucChot INT NOT NULL, SoLuongCan INT NOT NULL,
 PRIMARY KEY (MaYC,MaSPLinhKien), FOREIGN KEY (MaYC) REFERENCES YEU_CAU_LAP_RAP(MaYC), FOREIGN KEY (MaSPLinhKien) REFERENCES SAN_PHAM(MaSP),
 CONSTRAINT CK_NHU_CAU CHECK (DinhMucChot>0 AND SoLuongCan>0)
) ENGINE=InnoDB;


CREATE TABLE KET_QUA_LAP_RAP (
 MaKQ INT PRIMARY KEY AUTO_INCREMENT, MaYC INT NOT NULL, MaNVLap INT NOT NULL,
 MaNVTiepNhan INT NULL, SoLuongDat INT NOT NULL DEFAULT 0, SoLuongLoi INT NOT NULL DEFAULT 0,
 MaViTriDat INT NULL, MaViTriLoi INT NULL,
 TrangThai ENUM('NHAP','CHO_TIEP_NHAN','DA_TIEP_NHAN','TU_CHOI','HUY') NOT NULL DEFAULT 'NHAP',
 GhiChu VARCHAR(500), ThoiDiemTiepNhan DATETIME(6),
 FOREIGN KEY (MaYC) REFERENCES YEU_CAU_LAP_RAP(MaYC), FOREIGN KEY (MaNVLap) REFERENCES NHAN_VIEN(MaNV),
 FOREIGN KEY (MaNVTiepNhan) REFERENCES NHAN_VIEN(MaNV),
 FOREIGN KEY (MaViTriDat) REFERENCES VI_TRI_KHO(MaViTri), FOREIGN KEY (MaViTriLoi) REFERENCES VI_TRI_KHO(MaViTri),
 CONSTRAINT CK_KQ_SL CHECK (SoLuongDat>=0 AND SoLuongLoi>=0 AND SoLuongDat+SoLuongLoi>0),
 CONSTRAINT CK_KQ_VT CHECK ((SoLuongDat=0 OR MaViTriDat IS NOT NULL) AND (SoLuongLoi=0 OR MaViTriLoi IS NOT NULL)),
 CONSTRAINT CK_KQ_DUYET CHECK (MaNVTiepNhan IS NULL OR MaNVTiepNhan<>MaNVLap),
 CONSTRAINT CK_KQ_CHOT CHECK (TrangThai<>'DA_TIEP_NHAN' OR (MaNVTiepNhan IS NOT NULL AND ThoiDiemTiepNhan IS NOT NULL))
) ENGINE=InnoDB;


CREATE TABLE PHIEU_NHAP (
 MaPN INT PRIMARY KEY AUTO_INCREMENT,
 LoaiNhap ENUM('NCC','THANH_PHAM') NOT NULL,
 MaNCC INT NULL, MaNguonKetQua INT NULL UNIQUE,
 MaNVLap INT NOT NULL, NgayChungTu DATE NOT NULL, ThoiDiemGhiNhan DATETIME(6),
 TrangThai ENUM('NHAP','DA_GHI_NHAN','HUY') NOT NULL DEFAULT 'NHAP', GhiChu VARCHAR(255),
 FOREIGN KEY (MaNCC) REFERENCES NHA_CUNG_CAP(MaNCC),
 FOREIGN KEY (MaNguonKetQua) REFERENCES KET_QUA_LAP_RAP(MaKQ),
 FOREIGN KEY (MaNVLap) REFERENCES NHAN_VIEN(MaNV),
 CONSTRAINT CK_PN_NGUON CHECK (
  (LoaiNhap='NCC' AND MaNCC IS NOT NULL AND MaNguonKetQua IS NULL) OR
  (LoaiNhap='THANH_PHAM' AND MaNCC IS NULL AND MaNguonKetQua IS NOT NULL)),
 CONSTRAINT CK_PN_CHOT CHECK (TrangThai<>'DA_GHI_NHAN' OR ThoiDiemGhiNhan IS NOT NULL),
 INDEX IX_PN_NGAY (TrangThai,ThoiDiemGhiNhan)
) ENGINE=InnoDB;


CREATE TABLE CT_PHIEU_NHAP (
 MaCTPN INT PRIMARY KEY AUTO_INCREMENT, MaPN INT NOT NULL, MaSP INT NOT NULL, MaViTri INT NOT NULL,
 SoLuongNhan INT NOT NULL, SoLuongLoi INT NOT NULL DEFAULT 0, DonGiaNhap DECIMAL(15,2) NULL,
 KetQuaKiemTra VARCHAR(255),
 FOREIGN KEY (MaPN) REFERENCES PHIEU_NHAP(MaPN), FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP), FOREIGN KEY (MaViTri) REFERENCES VI_TRI_KHO(MaViTri),
 CONSTRAINT CK_CTPN_SL CHECK (SoLuongNhan>0 AND SoLuongLoi>=0 AND SoLuongLoi<=SoLuongNhan AND (DonGiaNhap IS NULL OR DonGiaNhap>=0))
) ENGINE=InnoDB;


CREATE TABLE PHIEU_XUAT (
 MaPX INT PRIMARY KEY AUTO_INCREMENT,
 LoaiXuat ENUM('CAP_PHAT','THANH_PHAM') NOT NULL,
 MaYCLapRap INT NULL, TenNguoiNhan VARCHAR(150) NULL,
 MaNVLap INT NOT NULL, MaNVDuyet INT NULL,
 NgayDeNghi DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), ThoiDiemThucHien DATETIME(6),
 TrangThai ENUM('NHAP','CHO_DUYET','DA_THUC_HIEN','TU_CHOI','HUY') NOT NULL DEFAULT 'NHAP',
 GhiChu VARCHAR(500), LyDoTuChoi VARCHAR(255),
 MaYCHieuLuc INT GENERATED ALWAYS AS (CASE WHEN LoaiXuat='CAP_PHAT' AND TrangThai IN('CHO_DUYET','DA_THUC_HIEN') THEN MaYCLapRap ELSE NULL END) STORED,
 UNIQUE (MaYCHieuLuc),
 FOREIGN KEY (MaYCLapRap) REFERENCES YEU_CAU_LAP_RAP(MaYC),
 FOREIGN KEY (MaNVLap) REFERENCES NHAN_VIEN(MaNV), FOREIGN KEY (MaNVDuyet) REFERENCES NHAN_VIEN(MaNV),
 CONSTRAINT CK_PX_NGUON CHECK (
  (LoaiXuat='CAP_PHAT' AND MaYCLapRap IS NOT NULL AND TenNguoiNhan IS NULL) OR
  (LoaiXuat='THANH_PHAM' AND MaYCLapRap IS NULL AND TenNguoiNhan IS NOT NULL AND CHAR_LENGTH(TRIM(TenNguoiNhan))>0)),
 CONSTRAINT CK_PX_DUYET CHECK (MaNVDuyet IS NULL OR MaNVDuyet<>MaNVLap),
 CONSTRAINT CK_PX_CHOT CHECK (TrangThai<>'DA_THUC_HIEN' OR (MaNVDuyet IS NOT NULL AND ThoiDiemThucHien IS NOT NULL)),
 INDEX IX_PX_NGAY (TrangThai,ThoiDiemThucHien)
) ENGINE=InnoDB;


CREATE TABLE CT_PHIEU_XUAT (
 MaCTPX INT PRIMARY KEY AUTO_INCREMENT, MaPX INT NOT NULL, MaSP INT NOT NULL, MaViTri INT NOT NULL,
 SoLuongXuat INT NOT NULL,
 UNIQUE (MaPX,MaSP,MaViTri),
 FOREIGN KEY (MaPX) REFERENCES PHIEU_XUAT(MaPX), FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP),
 FOREIGN KEY (MaViTri) REFERENCES VI_TRI_KHO(MaViTri),
 CONSTRAINT CK_CTPX_SL CHECK (SoLuongXuat>0)
) ENGINE=InnoDB;


CREATE TABLE BIEN_DONG_KHO (
 MaBienDong BIGINT PRIMARY KEY AUTO_INCREMENT, MaSP INT NOT NULL, MaViTri INT NOT NULL,
 LoaiBienDong ENUM('NHAP_NCC','NHAP_THANH_PHAM','CAP_PHAT','XUAT_THANH_PHAM') NOT NULL,
 DeltaThucTe INT NOT NULL, DeltaKhongBan INT NOT NULL DEFAULT 0,
 MaCTPN INT NULL UNIQUE, MaCTPX INT NULL UNIQUE,
 MaNV INT NOT NULL, ThoiDiem DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY (MaSP) REFERENCES SAN_PHAM(MaSP), FOREIGN KEY (MaViTri) REFERENCES VI_TRI_KHO(MaViTri),
 FOREIGN KEY (MaCTPN) REFERENCES CT_PHIEU_NHAP(MaCTPN), FOREIGN KEY (MaCTPX) REFERENCES CT_PHIEU_XUAT(MaCTPX),
 FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV),
 CONSTRAINT CK_BD_NGUON CHECK ((MaCTPN IS NOT NULL)+(MaCTPX IS NOT NULL)=1),
 CONSTRAINT CK_BD_TACDONG CHECK (
  (MaCTPN IS NOT NULL AND LoaiBienDong IN('NHAP_NCC','NHAP_THANH_PHAM') AND DeltaThucTe>0 AND DeltaKhongBan>=0 AND DeltaKhongBan<=DeltaThucTe) OR
  (MaCTPX IS NOT NULL AND LoaiBienDong IN('CAP_PHAT','XUAT_THANH_PHAM') AND DeltaThucTe<0 AND DeltaKhongBan=0)),
 INDEX IX_BD_KY (MaSP,MaViTri,ThoiDiem)
) ENGINE=InnoDB;


CREATE VIEW V_TON_KHO AS
 SELECT s.MaSP,s.SKU,s.TenSP,s.LoaiMatHang,s.DonViTinh,t.MaViTri,v.MaViTriHienThi,
 t.SoLuongThucTe,t.SoLuongKhongBan,t.SoLuongKhaDung
 FROM TON_KHO t JOIN SAN_PHAM s ON s.MaSP=t.MaSP JOIN VI_TRI_KHO v ON v.MaViTri=t.MaViTri;
CREATE VIEW V_TON_TONG AS
 SELECT s.MaSP,s.SKU,s.TenSP,s.LoaiMatHang,s.DonViTinh,
 COALESCE(SUM(t.SoLuongThucTe),0) SoLuongThucTe,
 COALESCE(SUM(t.SoLuongKhongBan),0) SoLuongKhongBan,
 COALESCE(SUM(t.SoLuongKhaDung),0) SoLuongKhaDung
 FROM SAN_PHAM s LEFT JOIN TON_KHO t ON t.MaSP=s.MaSP
 GROUP BY s.MaSP,s.SKU,s.TenSP,s.LoaiMatHang,s.DonViTinh;
-- Vat lieu tai khu lap rap DUOC TINH tu cap phat va ket qua, khong tao bang WIP rieng.
CREATE VIEW V_VAT_LIEU_LAP_RAP AS
 SELECT n.MaYC,n.MaSPLinhKien,n.DinhMucChot,n.SoLuongCan,
 IF(p.MaPX IS NULL,0,n.SoLuongCan) SoLuongDaCap,
 n.DinhMucChot*COALESCE(k.SoLuongDaXuLy,0) SoLuongDaDung,
 IF(p.MaPX IS NULL,0,n.SoLuongCan)-n.DinhMucChot*COALESCE(k.SoLuongDaXuLy,0) SoLuongCon
 FROM CT_NHU_CAU_LAP_RAP n
 LEFT JOIN PHIEU_XUAT p ON p.MaYCLapRap=n.MaYC AND p.LoaiXuat='CAP_PHAT' AND p.TrangThai='DA_THUC_HIEN'
 LEFT JOIN (SELECT MaYC,SUM(SoLuongDat+SoLuongLoi) SoLuongDaXuLy FROM KET_QUA_LAP_RAP WHERE TrangThai='DA_TIEP_NHAN' GROUP BY MaYC) k ON k.MaYC=n.MaYC;
CREATE VIEW V_NHU_CAU_LAP_RAP AS
 SELECT n.MaYC,n.MaSPLinhKien,s.SKU,n.DinhMucChot,n.SoLuongCan,
 v.SoLuongDaCap,COALESCE(t.SoLuongKhaDung,0) SoLuongKhaDung,
 GREATEST(0,n.SoLuongCan-v.SoLuongDaCap-COALESCE(t.SoLuongKhaDung,0)) SoLuongThieu
 FROM CT_NHU_CAU_LAP_RAP n JOIN SAN_PHAM s ON s.MaSP=n.MaSPLinhKien
 JOIN YEU_CAU_LAP_RAP y ON y.MaYC=n.MaYC
 JOIN V_VAT_LIEU_LAP_RAP v ON v.MaYC=n.MaYC AND v.MaSPLinhKien=n.MaSPLinhKien
 LEFT JOIN V_TON_TONG t ON t.MaSP=n.MaSPLinhKien WHERE y.TrangThai<>'HUY';
DELIMITER $$


CREATE PROCEDURE sp_kiem_tra_vai_tro(IN p_TK INT,IN p_Role VARCHAR(30),OUT p_NV INT)
BEGIN
 IF NOT EXISTS(SELECT 1 FROM TAI_KHOAN t JOIN NHAN_VIEN n ON n.MaNV=t.MaNV WHERE t.MaTK=p_TK AND t.TrangThai='HOAT_DONG' AND n.TrangThai='DANG_LAM' AND t.VaiTro=p_Role) THEN
 SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Tai khoan khong hoat dong hoac khong co quyen'; END IF;
 SELECT MaNV INTO p_NV FROM TAI_KHOAN WHERE MaTK=p_TK;
END$$


-- NOI BO: chi goi trong transaction nghiep vu, khong cap EXECUTE truc tiep.
CREATE PROCEDURE sp_ghi_bien_dong(IN p_SP INT,IN p_VT INT,IN p_TT INT,IN p_Loi INT,IN p_Type VARCHAR(30),IN p_CTPN INT,IN p_CTPX INT,IN p_NV INT)
BEGIN
 DECLARE v_State VARCHAR(20); DECLARE v_TT INT; DECLARE v_Loi INT;
 SELECT TrangThai INTO v_State FROM VI_TRI_KHO WHERE MaViTri=p_VT FOR UPDATE;
 IF v_State IS NULL OR v_State<>'HOAT_DONG' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Vi tri khong hoat dong'; END IF;
 INSERT INTO TON_KHO(MaSP,MaViTri) VALUES(p_SP,p_VT) ON DUPLICATE KEY UPDATE MaSP=MaSP;
 SELECT SoLuongThucTe,SoLuongKhongBan INTO v_TT,v_Loi FROM TON_KHO WHERE MaSP=p_SP AND MaViTri=p_VT FOR UPDATE;
 IF v_TT+p_TT<0 OR v_Loi+p_Loi<0 OR v_Loi+p_Loi>v_TT+p_TT THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Khong du ton kha dung'; END IF;
 UPDATE TON_KHO SET SoLuongThucTe=SoLuongThucTe+p_TT,SoLuongKhongBan=SoLuongKhongBan+p_Loi,NgayCapNhat=NOW(6),NguoiCapNhat=p_NV WHERE MaSP=p_SP AND MaViTri=p_VT;
 INSERT INTO BIEN_DONG_KHO(MaSP,MaViTri,LoaiBienDong,DeltaThucTe,DeltaKhongBan,MaCTPN,MaCTPX,MaNV)
 VALUES(p_SP,p_VT,p_Type,p_TT,p_Loi,p_CTPN,p_CTPX,p_NV);
END$$


CREATE PROCEDURE sp_ap_dung_nhap_noi_bo(IN p_PN INT,IN p_NV INT)
BEGIN
 DECLARE done INT DEFAULT 0; DECLARE c_ID INT; DECLARE c_SP INT; DECLARE c_VT INT; DECLARE c_SL INT; DECLARE c_Loi INT; DECLARE v_Type VARCHAR(20); DECLARE v_State VARCHAR(20);
 DECLARE cur CURSOR FOR SELECT MaCTPN,MaSP,MaViTri,SoLuongNhan,SoLuongLoi FROM CT_PHIEU_NHAP WHERE MaPN=p_PN ORDER BY MaSP,MaViTri,MaCTPN;
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET done=1;
 SELECT LoaiNhap,TrangThai INTO v_Type,v_State FROM PHIEU_NHAP WHERE MaPN=p_PN FOR UPDATE;
 IF v_State IS NULL OR v_State<>'NHAP' OR NOT EXISTS(SELECT 1 FROM CT_PHIEU_NHAP WHERE MaPN=p_PN) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu nhap chua hop le'; END IF;
 IF v_Type='NCC' AND EXISTS(SELECT 1 FROM CT_PHIEU_NHAP WHERE MaPN=p_PN AND DonGiaNhap IS NULL) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Nhap NCC can gia mua'; END IF;
 IF v_Type='THANH_PHAM' AND EXISTS(SELECT 1 FROM CT_PHIEU_NHAP WHERE MaPN=p_PN AND DonGiaNhap IS NOT NULL) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Nhap noi bo khong co gia von'; END IF;
 IF EXISTS(SELECT 1 FROM CT_PHIEU_NHAP c JOIN SAN_PHAM s ON s.MaSP=c.MaSP WHERE c.MaPN=p_PN AND (s.TrangThai<>'HOAT_DONG' OR (v_Type='NCC' AND s.LoaiMatHang<>'NGUYEN_LIEU') OR (v_Type='THANH_PHAM' AND s.LoaiMatHang<>'THANH_PHAM'))) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Loai mat hang khong dung loai nhap'; END IF;
 OPEN cur; l: LOOP FETCH cur INTO c_ID,c_SP,c_VT,c_SL,c_Loi; IF done THEN LEAVE l; END IF;
 CALL sp_ghi_bien_dong(c_SP,c_VT,c_SL,c_Loi,IF(v_Type='NCC','NHAP_NCC','NHAP_THANH_PHAM'),c_ID,NULL,p_NV);
 END LOOP; CLOSE cur;
 UPDATE PHIEU_NHAP SET TrangThai='DA_GHI_NHAN',ThoiDiemGhiNhan=NOW(6) WHERE MaPN=p_PN;
END$$


CREATE PROCEDURE sp_chot_nhap(IN p_MaTK INT, IN p_ID INT)
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_NV INT; DECLARE v_Type VARCHAR(20); DECLARE v_State VARCHAR(20);
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 CALL sp_kiem_tra_vai_tro(p_MaTK,'QUAN_LY_KHO',v_NV);
 
 SELECT LoaiNhap,TrangThai INTO v_Type,v_State FROM PHIEU_NHAP WHERE MaPN=p_ID FOR UPDATE;
 IF v_Type IS NULL OR v_Type<>'NCC' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Nhap thanh pham phai qua tiep nhan ket qua'; END IF;
 IF v_State='DA_GHI_NHAN' THEN COMMIT; SELECT p_ID MaDoiTuong,'DA_XU_LY_TRUOC' KetQua; LEAVE main; END IF;
 CALL sp_ap_dung_nhap_noi_bo(p_ID,v_NV);
 COMMIT; SELECT p_ID MaDoiTuong,'THANH_CONG' KetQua;
END$$


CREATE PROCEDURE sp_ban_hanh_bom(IN p_MaTK INT, IN p_ID INT)
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_NV INT; DECLARE v_SP INT; DECLARE v_State VARCHAR(20);
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 CALL sp_kiem_tra_vai_tro(p_MaTK,'QUAN_LY_KHO',v_NV);
 
 SELECT MaSPThanhPham,TrangThai INTO v_SP,v_State FROM BOM WHERE MaBOM=p_ID FOR UPDATE;
 IF v_State='DANG_AP_DUNG' THEN COMMIT; SELECT p_ID MaDoiTuong,'DA_XU_LY_TRUOC' KetQua; LEAVE main; END IF;
 IF v_SP IS NULL OR v_State<>'NHAP' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='BOM phai la ban nhap'; END IF;
 SELECT MaSP INTO v_SP FROM SAN_PHAM WHERE MaSP=v_SP FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM SAN_PHAM WHERE MaSP=v_SP AND LoaiMatHang='THANH_PHAM' AND TrangThai='HOAT_DONG') OR NOT EXISTS(SELECT 1 FROM CT_BOM WHERE MaBOM=p_ID) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='BOM can thanh pham va chi tiet'; END IF;
 IF EXISTS(SELECT 1 FROM CT_BOM c JOIN SAN_PHAM s ON s.MaSP=c.MaSPLinhKien WHERE c.MaBOM=p_ID AND (s.LoaiMatHang<>'NGUYEN_LIEU' OR s.TrangThai<>'HOAT_DONG')) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='BOM mot cap chi gom nguyen lieu'; END IF;
 UPDATE BOM SET TrangThai='NGUNG' WHERE MaSPThanhPham=v_SP AND TrangThai='DANG_AP_DUNG';
 UPDATE BOM SET TrangThai='DANG_AP_DUNG',NgayBanHanh=NOW(6) WHERE MaBOM=p_ID;
 COMMIT; SELECT p_ID MaDoiTuong,'THANH_CONG' KetQua;
END$$


CREATE PROCEDURE sp_giao_yeu_cau(IN p_MaTK INT, IN p_ID INT)
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_NV INT; DECLARE v_BOM INT; DECLARE v_SL INT; DECLARE v_State VARCHAR(30); DECLARE v_Nhan INT;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 CALL sp_kiem_tra_vai_tro(p_MaTK,'QUAN_LY_KHO',v_NV);
 
 SELECT MaBOM,SoLuongYeuCau,TrangThai,MaNVNhan INTO v_BOM,v_SL,v_State,v_Nhan FROM YEU_CAU_LAP_RAP WHERE MaYC=p_ID FOR UPDATE;
 IF v_State IN('DA_GIAO','DA_CAP_VAT_LIEU','DANG_LAP_RAP','HOAN_THANH') THEN COMMIT; SELECT p_ID MaDoiTuong,'DA_XU_LY_TRUOC' KetQua; LEAVE main; END IF;
