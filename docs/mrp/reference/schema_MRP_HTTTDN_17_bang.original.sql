CREATE PROCEDURE sp_duyet_xuat(IN p_MaTK INT, IN p_ID INT)
SQL SECURITY DEFINER
main: BEGIN
 DECLARE v_NV INT; DECLARE done INT DEFAULT 0; DECLARE c_ID INT; DECLARE c_SP INT; DECLARE c_VT INT; DECLARE c_SL INT;
 DECLARE v_Type VARCHAR(20); DECLARE v_YC INT; DECLARE v_State VARCHAR(20); DECLARE v_Lap INT; DECLARE v_Lock INT;
 DECLARE cur CURSOR FOR SELECT MaCTPX,MaSP,MaViTri,SoLuongXuat FROM CT_PHIEU_XUAT WHERE MaPX=p_ID ORDER BY MaSP,MaViTri;
 DECLARE CONTINUE HANDLER FOR NOT FOUND SET done=1;
 DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN ROLLBACK; RESIGNAL; END;
 START TRANSACTION;
 CALL sp_kiem_tra_vai_tro(p_MaTK,'QUAN_LY_KHO',v_NV);
 
 SELECT LoaiXuat,MaYCLapRap,TrangThai,MaNVLap INTO v_Type,v_YC,v_State,v_Lap FROM PHIEU_XUAT WHERE MaPX=p_ID FOR UPDATE;
 IF v_State='DA_THUC_HIEN' THEN COMMIT; SELECT p_ID MaDoiTuong,'DA_XU_LY_TRUOC' KetQua; LEAVE main; END IF;
 IF v_Type IS NULL OR v_State<>'CHO_DUYET' OR v_Lap=v_NV THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Phieu chua cho duyet hoac tu duyet'; END IF;
 IF v_Type='CAP_PHAT' THEN
 SELECT MaYC INTO v_Lock FROM YEU_CAU_LAP_RAP WHERE MaYC=v_YC FOR UPDATE;
 IF NOT EXISTS(SELECT 1 FROM YEU_CAU_LAP_RAP WHERE MaYC=v_YC AND TrangThai='DA_GIAO' AND DaNhanViec=1 AND MaNVNhan=v_Lap) THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Yeu cau khong con cho cap'; END IF;
 END IF;
 CALL sp_kiem_tra_dong_xuat(p_ID,v_Type,v_YC);
 SET done=0; OPEN cur; l: LOOP FETCH cur INTO c_ID,c_SP,c_VT,c_SL; IF done THEN LEAVE l; END IF;
 CALL sp_ghi_bien_dong(c_SP,c_VT,-c_SL,0,IF(v_Type='CAP_PHAT','CAP_PHAT','XUAT_THANH_PHAM'),NULL,c_ID,v_NV);
 END LOOP; CLOSE cur;
 IF v_Type='CAP_PHAT' THEN UPDATE YEU_CAU_LAP_RAP SET TrangThai='DA_CAP_VAT_LIEU' WHERE MaYC=v_YC; END IF;
 UPDATE PHIEU_XUAT SET TrangThai='DA_THUC_HIEN',MaNVDuyet=v_NV,ThoiDiemThucHien=NOW(6) WHERE MaPX=p_ID;
 COMMIT; SELECT p_ID MaDoiTuong,'THANH_CONG' KetQua;
END$$


