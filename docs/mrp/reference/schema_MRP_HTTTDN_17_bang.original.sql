CREATE PROCEDURE sp_bao_cao_kho(IN p_MaTK INT,IN p_Tu DATETIME(6),IN p_Den DATETIME(6))
BEGIN
 DECLARE v_NV INT;
 CALL sp_kiem_tra_vai_tro(p_MaTK,'QUAN_LY_KHO',v_NV);
 IF p_Tu IS NULL OR p_Den IS NULL OR p_Den<=p_Tu THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Khoang bao cao khong hop le'; END IF;
 SELECT s.MaSP,s.SKU,s.TenSP,s.LoaiMatHang,s.DonViTinh,b.MaViTri,
 SUM(IF(b.ThoiDiem<p_Tu,b.DeltaThucTe,0)) TonDauKy,
 SUM(IF(b.ThoiDiem>=p_Tu AND b.MaCTPN IS NOT NULL,b.DeltaThucTe,0)) NhapTrongKy,
 -SUM(IF(b.ThoiDiem>=p_Tu AND b.MaCTPX IS NOT NULL,b.DeltaThucTe,0)) XuatTrongKy,
 SUM(b.DeltaThucTe) TonCuoiKy,SUM(b.DeltaKhongBan) KhongBanCuoiKy,
 SUM(b.DeltaThucTe-b.DeltaKhongBan) KhaDungCuoiKy
 FROM BIEN_DONG_KHO b JOIN SAN_PHAM s ON s.MaSP=b.MaSP WHERE b.ThoiDiem<p_Den
 GROUP BY s.MaSP,s.SKU,s.TenSP,s.LoaiMatHang,s.DonViTinh,b.MaViTri ORDER BY s.SKU,b.MaViTri;
END$$


