 UPDATE KET_QUA_LAP_RAP SET TrangThai='DA_TIEP_NHAN',MaNVTiepNhan=v_NV,ThoiDiemTiepNhan=NOW(6) WHERE MaKQ=p_ID;
 UPDATE YEU_CAU_LAP_RAP SET TrangThai=IF(v_Da+v_Dat+v_Loi=v_KeHoach,'HOAN_THANH','DANG_LAP_RAP') WHERE MaYC=v_YC;
